  const bicSpots = buildElectronicsStores(BIC_CAMERA_SEED, 'Bic Camera', stationsList);
  const yodobashiSpots = buildElectronicsStores(YODOBASHI_SEED, '友都八喜 (Yodobashi)', stationsList);
  const kojimaSpots = buildElectronicsStores(KOJIMA_BIC_SEED, 'Kojima × Bic Camera', stationsList);
  const sofmapSpots = buildElectronicsStores(SOFMAP_SEED, 'Sofmap (ソフマップ)', stationsList);

  const combined = [...bicSpots, ...yodobashiSpots, ...kojimaSpots, ...sofmapSpots];
