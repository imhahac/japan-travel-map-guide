export function buildElectronicsStores(seedList, brandName, stationsList = []) {
  return seedList.map(item => {
    let nearestStation = item.name.includes('站') || item.name.includes('空港') ? item.name : `${item.prefecture}主要車站`;
    let stationLine = 'JR / 地鐵 / 私鐵';
    let walkMin = 2;

    const matched = stationsList.find(st => 
      item.address.includes(st.name.replace(/站$/, '')) || 
      item.name.includes(st.name.replace(/站$/, ''))
    );

    if (matched) {
      nearestStation = matched.name;
      stationLine = matched.lines?.[0] || 'JR / 地鐵';
    }

    let defaultImg = 'https://images.unsplash.com/photo-1550009158-9ebf69173e03?auto=format&fit=crop&w=800&q=80';
    if (brandName.includes('Yodobashi') || brandName.includes('友都八喜')) {
      defaultImg = 'https://images.unsplash.com/photo-1526738549149-8e07eca6c147?auto=format&fit=crop&w=800&q=80';
    } else if (brandName.includes('Sofmap')) {
      defaultImg = 'https://images.unsplash.com/photo-1511512578047-dfb367046420?auto=format&fit=crop&w=800&q=80';
    }

    return {
      id: item.code,
      category: '購物藥妝',
      brand: brandName,
      name: item.name,
      nameJa: item.nameJa,
      region: item.region,
      prefecture: item.prefecture,
      nearestStation,
      stationLine,
      stationAccess: `鄰近 ${nearestStation} 步行約 ${walkMin} 分鐘`,
      walkMinutes: walkMin,
      address: item.address,
      coordinates: `${item.lat}, ${item.lng}`,
      lat: item.lat,
      lng: item.lng,
      phone: item.phone,
      bookingUrl: item.url,
      googleMapUrl: `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(item.nameJa)}`,
      imageUrl: defaultImg,
      images: [defaultImg],
      tags: item.tags.join(', '),
      notes: item.notes
    };
  });
}

